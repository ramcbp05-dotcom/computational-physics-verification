"""Check the committed error report against a freshly generated one.

Why this is not ``git diff``
----------------------------
The report mixes two kinds of number, and only one of them is reproducible.

A quantity that is zero in exact arithmetic (an operator commutator, the
unitarity residual, Boris speed conservation, leapfrog angular momentum) is
measured as pure round-off, somewhere around 1e-16 to 1e-13. Its *value* is a
property of the machine: the summation order inside the BLAS, the FMA
instructions available, the CPU. Across two machines the same correct code
gives 2.205e-14 and 1.795e-14 for the same quantity, and neither is more right
than the other. A byte-exact diff therefore fails on every runner that is not
the one the report was written on, which makes the check worthless in the way
that matters: a check that always fails gets ignored, and then it is not
checking anything.

A discretisation error (leapfrog's energy drift, the E x B drift, a fitted
convergence order) is reproducible to about three significant figures,
because it is set by the step size rather than by round-off.

So this script compares structure exactly and numbers by magnitude:

* the non-numeric text of every line must match exactly, which is what catches
  a stale report (a heading or column name changed in the generator but never
  regenerated here);
* two numbers both at or below ``ROUNDOFF`` agree by definition (they are
  both reports of the same exact zero;
* otherwise they must agree to within ``REL_TOL``.

A genuinely weakened bound) leapfrog's energy drift moving from 2.7e-05 to
1e-03 (is far outside both rules and still fails, which is the whole point of
committing the report.

One wrinkle worth naming, because the first version of this script got it
wrong. The generator prints an exact zero as the words ``0 (exact)`` and
anything else as a number. Whether a round-off quantity lands on exactly 0.0 or
on 1.3e-16 is machine-dependent, so the same measurement can print as words on
one machine and as a number on another. Comparing text first, that reads as a
structural change rather than as the round-off difference it is) so
``0 (exact)`` is normalised to ``0`` before anything else happens.
"""

from __future__ import annotations

import argparse
import re
import subprocess
import sys
from pathlib import Path

ROUNDOFF = 1e-12
REL_TOL = 0.02

NUMBER = re.compile(r"[-+]?\d*\.?\d+(?:[eE][-+]?\d+)?")
PLACEHOLDER = "\x00"

# The generator's spelling of an exact zero. Normalised to a plain 0 so that a
# quantity printing as words here and as 1.3e-16 elsewhere is compared as the
# round-off difference it is, not as changed text.
EXACT_ZERO = re.compile(r"0 \(exact\)")

# The provenance line carries a timestamp and the NumPy version, both of which
# are expected to differ on every run and on every machine.
EXEMPT = re.compile(r"^Generated by `scripts/error_report\.py`")

REPO_ROOT = Path(__file__).resolve().parent.parent
DEFAULT_REPORT = REPO_ROOT / "results" / "numerical-error-report.md"


def normalise(text: str) -> str:
    """Spell exact zeros uniformly, and ignore trailing blank lines.

    ``--print`` adds a newline of its own, so the generated text carries one
    more trailing blank line than the file on disk. That is not a structural
    change.
    """
    return EXACT_ZERO.sub("0", text).rstrip("\n")


def skeleton(line: str) -> str:
    """The line with every number replaced, so text can be compared alone."""
    return NUMBER.sub(PLACEHOLDER, line)


def numbers(line: str) -> list[float]:
    return [float(m.group()) for m in NUMBER.finditer(line)]


def agree(old: float, new: float) -> tuple[bool, str]:
    """Compare one measured pair. Returns (ok, how it was judged)."""
    if old == new:
        return True, "identical"
    if abs(old) <= ROUNDOFF and abs(new) <= ROUNDOFF:
        return True, f"both at round-off (<= {ROUNDOFF:.0e})"
    scale = max(abs(old), abs(new))
    rel = abs(old - new) / scale
    if rel <= REL_TOL:
        return True, f"relative change {rel:.2e} <= {REL_TOL:.0%}"
    return False, f"relative change {rel:.2e} exceeds {REL_TOL:.0%}"


def compare(committed: str, regenerated: str) -> tuple[list[str], list[str]]:
    """Returns (failures, tolerated) as human-readable lines."""
    old_lines = normalise(committed).splitlines()
    new_lines = normalise(regenerated).splitlines()
    failures: list[str] = []
    tolerated: list[str] = []

    if len(old_lines) != len(new_lines):
        failures.append(
            f"the report changed length: {len(old_lines)} lines committed, "
            f"{len(new_lines)} regenerated. The structure of the report "
            f"changed, not just a measurement: regenerate and commit it."
        )
        return failures, tolerated

    for n, (old, new) in enumerate(zip(old_lines, new_lines), start=1):
        if old == new or EXEMPT.match(old):
            continue
        if skeleton(old) != skeleton(new):
            failures.append(
                f"line {n}: the text changed, which means the committed report "
                f"is stale. Run `python scripts/error_report.py` and commit "
                f"the result.\n    committed:   {old}\n    regenerated: {new}"
            )
            continue
        for old_value, new_value in zip(numbers(old), numbers(new)):
            if old_value == new_value:
                continue
            ok, how = agree(old_value, new_value)
            entry = f"line {n}: {old_value:.6g} -> {new_value:.6g} ({how})"
            if ok:
                tolerated.append(entry)
            else:
                failures.append(f"{entry}\n    in: {new.strip()}")

    return failures, tolerated


def regenerate() -> str:
    """A fresh report on stdout, leaving the committed file untouched.

    ``--print`` matters here: an earlier version regenerated in place and then
    diffed against git, which left the working tree dirty after every test run
    and made the check depend on git history being present.
    """
    done = subprocess.run(
        [sys.executable, str(REPO_ROOT / "scripts" / "error_report.py"), "--print"],
        capture_output=True, text=True, cwd=REPO_ROOT,
    )
    if done.returncode != 0:
        raise RuntimeError(f"error_report.py failed:\n{done.stderr}")
    return done.stdout


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--report", type=Path, default=DEFAULT_REPORT,
        help="the committed report to check (default: %(default)s)",
    )
    args = parser.parse_args()

    if not args.report.is_file():
        print(f"error: {args.report} does not exist")
        return 2

    failures, tolerated = compare(args.report.read_text(), regenerate())

    if tolerated:
        print(f"{len(tolerated)} measurement(s) moved within tolerance:")
        for line in tolerated:
            print(f"  {line}")
        print()

    if failures:
        print(f"{len(failures)} problem(s) found:")
        for line in failures:
            print(f"  {line}")
        return 1

    print(
        f"report is current: structure identical, and every measurement either "
        f"matches or sits inside tolerance "
        f"(round-off <= {ROUNDOFF:.0e}, otherwise {REL_TOL:.0%})."
    )
    return 0


if __name__ == "__main__":
    sys.exit(main())
